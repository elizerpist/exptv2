    val shadowReason: KeyguardSurfaceReason? = null,
    val rawHost: Int = 0,
    val rawEntry: Int = 0,
    val rawClock: Int = 0,
    val rejectedUnverified: Int = 0,
    val rejectedAncestry: Int = 0,
    val rejectedExcluded: Int = 0,
    val rejectedForeign: Int = 0,
